"""Build CatQuest/PlaceLore.lua from the server-synchronised place manifest."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "docs/places/voiced.json"
ZONES = ROOT / "docs/places/zones"
BOOK_DATA = ROOT / "CatQuest/BookData.lua"
OUT = ROOT / "CatQuest/PlaceLore.lua"


def lua_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def load_places() -> dict[str, dict]:
    result = {}
    for path in sorted(ZONES.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        for place in data.get("places", []):
            text = " ".join(str(place.get("text") or "").split())
            if not text or not place.get("subzone"):
                continue
            import hashlib
            digest = hashlib.md5(text.encode("utf-8")).hexdigest()[:8]
            result[digest] = {**place, "zone": data["zone"], "text": text}
    return result


def main() -> int:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    places = load_places()
    old = set(re.findall(r'^    \["([0-9a-f]{8})"\] = \{', BOOK_DATA.read_text(encoding="utf-8"), re.M))
    clash = sorted(set(manifest) & old)
    if clash:
        raise SystemExit("hash already used by CatQuest Books: " + ", ".join(clash))
    selected = []
    for digest, meta in manifest.items():
        place = places.get(digest)
        if not place or not isinstance(meta, dict) or not meta.get("cues"):
            continue
        selected.append((place["zone"], place["subzone"], digest, meta, place))
    selected.sort()
    out = [
        "-- Generated by scripts/build_place_lore.py from docs/places/voiced.json. Do not edit.",
        "local data = CatQuest335Books",
        "data.books = data.books or {}",
        "data.places = data.places or {}",
        "data.placeAreas = data.placeAreas or {}",
        "data.placeInstances = data.placeInstances or {}",
        "local books, places, placeAreas, placeInstances = data.books, data.places, data.placeAreas, data.placeInstances",
    ]
    for zone, subzone, digest, meta, _ in selected:
        cues = ", ".join("{ %.2f, %s }" % (float(t), lua_string(str(s))) for t, s in meta["cues"])
        out.append('books["%s"] = { d = %.1f, v = "narrator", c = { x = { %s } } }' %
                   (digest, float(meta.get("d") or 0), cues))
    zones = {}
    for zone, subzone, digest, _, place in selected:
        zones.setdefault(zone, []).append((subzone, digest, place.get("area_id")))
    for zone, entries in sorted(zones.items()):
        out.append(f"places[{lua_string(zone)}] = places[{lua_string(zone)}] or {{}}")
        out.append(f"placeAreas[{lua_string(zone)}] = placeAreas[{lua_string(zone)}] or {{}}")
        for subzone, digest, area_id in sorted(entries):
            out.append(f"places[{lua_string(zone)}][{lua_string(subzone)}] = \"{digest}\"")
            if isinstance(area_id, int) and area_id > 0:
                out.append(f"placeAreas[{lua_string(zone)}][{lua_string(subzone)}] = {area_id}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(selected)} places in {len(zones)} zones")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
