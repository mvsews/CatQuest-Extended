-- Interface language: Russian or English by choice (/cq ui, options), else
-- the client's. On Lasthavens the choice survives F5 in Bridge.lua, which the
-- extension puts first in the TOC so texts made at load use it too.
ns.UI_LOCALES = { "ruRU", "enUS" }
function ns.UIChoice()
    local choice = ns.db and ns.db.uiLanguage
    if choice == nil then
        choice = CatQuest335_BridgeUI
    end
    if choice == "ruRU" or choice == "enUS" then
        return choice
    end
    return "auto"
end

function ns.UILocale()
    local choice = ns.UIChoice()
    return choice ~= "auto" and choice or ns.ClientLocale()
end

-- Missing keys fall back to English, then to the key itself.
ns.L = setmetatable({}, {
    __index = function(_, key)
        local active = STRINGS[ns.UILocale()] or STRINGS.enUS
        return active[key] or STRINGS.enUS[key] or key
    end,
})

