local ns = CatQuest335 or {}
CatQuest335 = ns

-- Voice locales the server can produce. The interface language always follows
-- the client (GetLocale), because 3.3.5 fonts only carry their own glyphs.
ns.VOICE_LOCALES = { "ruRU", "enUS", "zhCN", "zhTW", "deDE", "frFR", "esES", "esMX", "ptBR", "koKR", "itIT" }
local LOCALE_ALIASES = { enGB = "enUS", ptPT = "ptBR" }

-- Short codes for typing in chat: /cq lang ru | en | cn ... (any case).
ns.SHORT_LOCALES = {
    ru = "ruRU", en = "enUS", cn = "zhCN", zh = "zhCN", tw = "zhTW", de = "deDE",
    fr = "frFR", es = "esES", mx = "esMX", br = "ptBR", pt = "ptBR", kr = "koKR",
    ko = "koKR", it = "itIT",
}
local SHORT_OF = {}
for short, locale in pairs(ns.SHORT_LOCALES) do
    -- The first, most natural code wins for display: cn, not zh; br, not pt.
    if not SHORT_OF[locale] or (short == "cn" or short == "br" or short == "kr") then
        SHORT_OF[locale] = short
    end
end

function ns.ShortLocale(locale)
    return SHORT_OF[locale or ""] or tostring(locale or "")
end

function ns.NormalizeLocale(value)
    -- Accept "ru", "CN", "zh_CN", "zh-cn" and "zhcn" as well as "zhCN".
    value = string.gsub(tostring(value or ""), "[%-_%s]", "")
    local short = ns.SHORT_LOCALES[string.lower(value)]
    if short then
        return short
    end
    if string.len(value) == 4 then
        value = string.lower(string.sub(value, 1, 2)) .. string.upper(string.sub(value, 3, 4))
    end
    value = LOCALE_ALIASES[value] or value
    for i = 1, #ns.VOICE_LOCALES do
        if string.lower(ns.VOICE_LOCALES[i]) == string.lower(value) then
            return ns.VOICE_LOCALES[i]
        end
    end
end

function ns.ClientLocale()
    return ns.NormalizeLocale(GetLocale and GetLocale()) or "enUS"
end

