-- Exercise the real Core scheduler, not a replacement ns.PlayQuest.
local ns=CatQuest335
local now=1000
local sounds,music,writes={},{},{}
local cvars={Sound_EnableMusic="1",Sound_MusicVolume="0.4",Sound_EnableSFX="1"}
local available=true
local musicResult=nil
local musicThrows=false
function GetTime() return now end
function time() return math.floor(now) end
function GetCVar(key) return cvars[key] or "1" end
function SetCVar(key,value) cvars[key]=tostring(value);writes[#writes+1]={key,value} end
function PlaySoundFile(path,channel)
    sounds[#sounds+1]={path=path,channel=channel}
    return available
end
function PlayMusic(path)
    music[#music+1]=path
    if musicThrows then error("music unavailable") end
    return musicResult
end
function StopMusic() end
local ids={9857,9858,9859}
local entry={quests=ids}
local function reset(channel,queue,ready)
    ns.Stop(true)
    now=now+1000
    sounds,music,writes={},{},{}
    available=true;musicResult=nil;musicThrows=false
    ns.state.lastRequestKey=nil
    ns.db.volumeChannel=channel or "SFX"
    ns.db.queue=queue~=false
    ns.db.trackGap=0
    ns.completedQuests={[9857]=true,[9858]=true,[9859]=true}
    CatQuest335_BridgeReady={locale="ruRU",q=ready and {[9857]=1,[9858]=1,[9859]=1} or {},
        d={[9857]={23,0},[9858]={38.2,0},[9859]={47.1,0}}}
end
local function tick(seconds) now=now+seconds;ns.OnUpdate() end

-- Stale startup index: a newly generated cached track is still on-demand.
-- Successful playback must claim active before the next chapter entry.
reset("SFX",true,true)
assert(ns.StoryListen(entry)==3)
assert(#sounds==1 and ns.state.active.questID==9857 and #ns.state.queue==2)
assert(ns.StoryListen(entry)==0 and #sounds==1 and #ns.state.queue==2)
tick(22);assert(#sounds==1)
tick(1.2);tick(0)
assert(#sounds==2 and ns.state.active.questID==9858)
tick(30);assert(#sounds==2 and ns.state.active.questID==9858)
tick(8.4);tick(0)
assert(#sounds==3 and ns.state.active.questID==9859)
tick(47.3);tick(0)
assert(not ns.state.active and #ns.state.queue==0)

-- A chapter retains all its lines when dialogue queueing is disabled.
reset("SFX",false,true)
assert(ns.StoryListen(entry)==3 and ns.db.queue==false)
assert(#sounds==1 and ns.state.active.questID==9857 and #ns.state.queue==2)

-- A missing first file must not block later ready lines. The second line is
-- allowed to play while the first one remains in the pending retry queue.
reset("SFX",true,true);available=false
local firstMissing=true
function PlaySoundFile(path,channel)
    sounds[#sounds+1]={path=path,channel=channel}
    return not (firstMissing and path:find("9857"))
end
assert(ns.StoryListen(entry)==3)
assert(#sounds>=2 and #ns.state.pending==1 and ns.state.pending[1].questID==9857
    and ns.state.active and ns.state.active.questID==9858 and #ns.state.queue==1)
assert(ns.StoryListen(entry)==0 and #sounds>=2)
firstMissing=false;available=true;tick(40);tick(0)
assert(ns.state.active and ns.state.active.questID==9857 and #ns.state.pending==0 and #ns.state.queue==1)
ns.Stop(true);local count=#sounds;tick(400)
assert(#sounds==count and not ns.state.active and #ns.state.pending==0 and #ns.state.queue==0)

-- A successful retry is also an active track, never anonymous.  The current
-- readiness bridge may acknowledge the quest path itself before a poll slot
-- is needed; either route must still claim the real quest item.
reset("SFX",true,false);available=false
assert(ns.StoryListen(entry)==3)
function PlaySoundFile(path,channel)
    sounds[#sounds+1]={path=path,channel=channel}
    return path:find("poll")~=nil
end
tick(9)
assert(#sounds>=1 and ns.state.active and ns.state.active.questID==9857)
assert(#ns.state.pending==0 and #ns.state.queue==2)
tick(1);assert(#sounds>=1)

-- Dynamic generation retains its SFX/poll transport in Music mode: the
-- nil PlayMusic result cannot acknowledge whether generated bytes exist.
reset("Music",true,false)
function PlaySoundFile(path,channel) sounds[#sounds+1]={path=path,channel=channel};return true end
assert(ns.StoryListen(entry)==3)
assert(#sounds==1 and #music==0 and ns.state.active.playChannel=="SFX" and #ns.state.queue==2)

-- PlayMusic in 3.3.5 has no reliable success return. Nil or false must
-- never trigger a second call through SFX, nor a 0 -> 1 music toggle.
for _,result in ipairs({"nil","false"}) do
    reset("Music",true,true)
    if result=="false" then musicResult=false end
    assert(ns.StoryListen(entry)==3)
    assert(#music==1 and #sounds==0 and ns.state.active.playChannel=="Music")
    assert(ns.StoryListen(entry)==0 and #music==1 and #sounds==0)
    for _,write in ipairs(writes) do
        assert(write[1]~="Sound_EnableMusic" or tostring(write[2])~="0")
    end
    ns.Stop(true)
    assert(music[#music]:find("stop%-voice") and #sounds==0)
    assert(cvars.Sound_MusicVolume=="0.4")
    count=#music;tick(400);assert(#music==count)
end

-- An actual Music exception must not silently fall back to another channel.
reset("Music",true,true);musicThrows=true
assert(ns.PlayQuest(9857,"quest",true,false))
assert(#music==1 and #sounds==0 and not ns.state.active and #ns.state.pending==1)

-- Installed recordings use the same single-call rule, including clients
-- returning nil for successful PlayMusic and false for a missing sound.
local function localItem()
    return {key="local-test",questID=9856,kind="quest",title="Local",file="local.ogg",duration=32.7,cues={}}
end
reset("Music",true,true);cvars.Sound_EnableMusic="0"
assert(ns.PlayItem(localItem(),true))
assert(#music==1 and #sounds==0 and ns.state.active.playChannel=="Music")
ns.Stop(true);assert(cvars.Sound_EnableMusic=="0")
reset("SFX",true,true)
function PlaySoundFile(path,channel) sounds[#sounds+1]={path=path,channel=channel};return false end
assert(ns.PlayItem(localItem(),true))
assert(#sounds==1 and #music==0 and not ns.state.active)
